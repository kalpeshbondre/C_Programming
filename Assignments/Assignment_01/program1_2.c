#include <stdio.h>
#include <stdlib.h>

///////////////////////////////////////////////////////////////////////////////////////////////
// 
// Function Name : Display
//  Input         : None
//  Output        : None
//  Description   : Displays "Marvellous" five times
//  Date          : 19/10/2026
//  Author        : Kalpesh Balappa Bondre
//
///////////////////////////////////////////////////////////////////////////////////////////////

void Display()
{
    int iCnt = 0;

    for(iCnt = 1; iCnt <= 5 ; iCnt++)
    {
        printf("Marvellous \n");
    }
}

///////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point of the Application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    //Function call
    Display();

    return EXIT_SUCCESS;
}