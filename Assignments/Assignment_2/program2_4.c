void Display(int iNo , int iFrequency)
{
    int iCnt = 0;

    //Input Updater
    if( iFrequency < 0)
    {
        iFrequency = -(iFrequency);
    }
    
    //Business Logic
    for(iCnt = 1; iCnt <= iFrequency ; iCnt++)
    {
        printf("%d\t",iNo);
    }
}

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iCount = 0;

    printf("Enter number : \n");
    scanf("%d",&iValue);

    printf("Enter frequency: \n");
    scanf("%d",&iCount);

    //Function call
    Display(iValue,iCount);

    return EXIT_SUCCESS;
}

