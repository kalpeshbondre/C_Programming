#include <stdio.h>
#include <stdlib.h>

///////////////////////////////////////////////////////////////////////////////////////////////
//  
//  Function name   :   Display
//  Input           :   None
//  Output          :   None
//  Description     :   Program to print 5 to 1 number on screen
//  Date            :   19/10/2026
//  Author          :   Kalpesh Balappa Bondre
//
///////////////////////////////////////////////////////////////////////////////////////////////

void Display()
{
    int iCnt = 0;
    iCnt = 5;
    while (iCnt >= 1)
    {
        printf("%d \n",iCnt);
        iCnt--;
    }
}

///////////////////////////////////////////////////////////////////////////////////////////////
//
//      Entry point of the Application
//
///////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    //Function Call
    Display();

    return EXIT_SUCCESS;
}