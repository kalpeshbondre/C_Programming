
#include <stdio.h>
#include <stdlib.h>

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name  : CheckLeapYear
//  Input          : Integer
//  Output         : None
//  Description    : Checks whether the given year is a leap year according to Gregorian calendar rules.
//  Date           : 22/10/2026
//  Author         : Kalpesh Bondre
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void CheckLeapYear(int iYear)
{
    if(iYear <= 0)
    {
        printf("Invalid Input\n");
        return;
    }

    if((iYear % 400 == 0) || ((iYear % 4 == 0) && (iYear % 100 != 0)))
    {
        printf("%d is Leap Year\n", iYear);
    }
    else
    {
        printf("%d is Not Leap Year\n", iYear);
    }
}

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point function
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iYear = 0;

    printf("Enter the Year: ");
    scanf("%d", &iYear);

    CheckLeapYear(iYear);

    return EXIT_SUCCESS;
}

