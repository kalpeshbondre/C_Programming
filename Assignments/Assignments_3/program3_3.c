void DisplayEvenFactor(int iNo)
{
    //Counter
    int iCnt = 0;

    //Input Updater
    if(iNo <= 0)
    {
        iNo = -iNo;
    }

    //Business Logic
    for(iCnt = 1; iCnt <= (iNo/2); iCnt++)
    {
        if((iCnt % 2 == 0) && ((iNo % iCnt) == 0))
        {
            printf("%d ",iCnt);
        }
    }

}

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point of the function
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number \n");
    scanf("%d",&iValue);

    //Function Call
    DisplayEvenFactor(iValue);

    return EXIT_SUCCESS;
}
