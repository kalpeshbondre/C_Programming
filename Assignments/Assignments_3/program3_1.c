void PrintEven(int iNo)
{
    //Filter
    if(iNo <= 0)
    {
        return;
    }

    int iCnt = 0;

    //Business Logic
    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        printf("%d ",iCnt*2);
    }
}

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point function
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue =0;

    printf("Enter number \n");
    scanf("%d",&iValue);

    PrintEven(iValue);

    return EXIT_SUCCESS;
}

