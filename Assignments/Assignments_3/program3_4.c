#include<stdio.h>
#include<stdlib.h>
#include<ctype.h> 

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function name   :   DisplayConvert
//  Input           :   Character
//  Output          :   None
//  Description     :   Accept one character from user and convert case of that character.
//  Date            :   20/10/2026
//  Author          :   Kalpesh Balappa Bondre
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void DisplayConvert(char cNo)
{
    if(islower(cNo))
    {
        printf("Converted: %c\n",toupper(cNo));
    } 
    else if (isupper(cNo)) 
    {
        printf("Converted: %c\n", tolower(cNo));
    } 
    else {
        printf("Character is not a letter: %c\n", cNo);
    }
}
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point function
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char cValue;
    printf("Enter character\n");
    scanf(" %c",&cValue);

    DisplayConvert(cValue);

    return EXIT_SUCCESS;
}

