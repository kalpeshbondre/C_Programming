#include <stdio.h>
#include <stdlib.h>

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//      Function Name   :   DisplayASCII
//      Input           :   None
//      Output          :   None
//      Description     :   Displays ASCII table with symbol, Decimal, Hexadecimal and Octal values (0 to 255)
//      Date            :   11/11/2026
//      Author          :   Kalpesh Balappa Bondre
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void DisplayASCII()
{
    int iCnt = 0;

    printf("---------------------------------------------------------\n");
    printf("Symbol\t\tDecimal\t\tHexadecimal\tOctal\n");
    printf("---------------------------------------------------------\n");

    for(iCnt = 0; iCnt <= 255; iCnt++)
    {
        printf("%c\t\t%d\t\t0x%X\t\t0%o\n", iCnt, iCnt, iCnt, iCnt);
    }

    printf("---------------------------------------------------------\n");
}

//////////////////////////////////////////////////////////////////////////////////////////////////
//
//      Main Entry Point Function
//
//////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    DisplayASCII();

    return EXIT_SUCCESS;
}

